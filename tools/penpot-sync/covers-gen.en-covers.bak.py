# Writes cover-phone.html (390 px) and cover-desktop.html (1440 px): overview covers with a thumbnail of every board.
# Thumbnails come from thumbs.py. Tiles carry data-board="<board name>" so push.mjs can link each one to its board.
import json, os, html

D = os.path.dirname(os.path.abspath(__file__))
pages = json.load(open(os.path.join(D, "pages.json"), encoding="utf-8"))


def slug(n):
    return "".join(c if c.isalnum() else "_" for c in n).strip("_")


SHORT = {
    "01": "Home", "02": "Raja Ampat", "03": "North Sulawesi", "04": "Yacht charters", "05": "Guest stories", "06": "About us",
    "07": "Travel agents", "08": "Plan your trip", "09": "Thank you · traveller", "10": "Thank you · agent",
    "11": "Privacy & cookies", "12": "Booking terms", "13": "404 page", "14": "Maintenance",
    "S1": "Cookie banner", "S2": "Cookie settings", "S3": "Form errors", "S4": "Sending failed", "M1": "Menu open",
}
OTHER = {"E1": "Auto-reply · traveller", "E2": "Auto-reply · agent", "E3": "New enquiry · owner", "P1": "Link previews",
         "A1": "Admin · Enquiries", "A2": "Admin · Reviews", "A3": "Admin · Photos & video", "A4": "Admin · Prices"}
HOW = ["Grey box with a cross = photo or video to come", "Grey lines = text to come",
       "Labels like “01 · Hero” = block numbers: use them in comments",
       "No colours, fonts or final copy yet: that comes in Stage 2 (design)"]
MOVE_PHONE = ["Scroll like on a phone. ☰ opens the menu; buttons and links work.",
              "The arrows at the screen edges step through all 20 screens in order.",
              "The bottom bar (Plan your trip · WhatsApp) appears after the first screen and hides over forms and the footer. Penpot cannot hide it, so here it always shows.",
              "Not clickable on purpose: WhatsApp, email, Instagram, PDF downloads, “View all photos” and jumps within a page."]
THIS_DESK = ["Press Start and click through like a real site, or click any page above to jump to it.",
             "The arrows at the screen edges step through all 19 screens in order.",
             "Other pages of this file (menu at the top left): Mobile · Emails & previews · Admin.",
             "Not clickable on purpose: WhatsApp, email, Instagram, PDF downloads, “View all photos” and jumps within a page. The days slider works in the HTML prototype; here it shows 7 days."]


def li(xs):
    return "".join(f"<li>{html.escape(x)}</li>" for x in xs)


def tile(b):
    code = b["name"].split(" ")[0]
    return (f'<a class="tile" data-board="{html.escape(b["name"])}"><img src="thumbs/{slug(b["name"])}.jpg" alt="">'
            f'<span class="cap"><b>{code}</b> {html.escape(SHORT[code])}</span></a>')


def otile(b):
    code = b["name"].split(" ")[0]
    return (f'<div class="tile"><img src="thumbs/{slug(b["name"])}.jpg" alt="">'
            f'<span class="cap"><b>{code}</b> {html.escape(OTHER[code])}</span></div>')


def site(g):
    bs = [b for b in pages if b["group"] == g]
    main = [b for b in bs if b["name"][:2].isdigit() and int(b["name"][:2]) <= 10]
    return main, [b for b in bs if b not in main]


def head(w, title, css):
    return ("<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">"
            f"<meta name=\"viewport\" content=\"width={w}\"><title>{title}</title>\n"
            "<!-- Generated by covers-gen.py: source of the \"00 Cover\" board in Penpot (cover-build.cjs, then push.mjs newcovers). -->\n"
            "<style>\n@import url('https://fonts.googleapis.com/css2?family=Inter:wght@400;600;700&display=swap');\n"
            "*{box-sizing:border-box;margin:0;padding:0} a{color:inherit;text-decoration:none}\n"
            f"body{{width:{w}px;background:#fff;color:#1f1f1f;font-family:'Inter',sans-serif;line-height:1.45}}\n"
            + css + "\n</style></head><body>")


