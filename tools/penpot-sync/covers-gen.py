def ru(n, one, few, many):
    n = abs(n) % 100
    if 10 < n < 20: return many
    n %= 10
    return one if n == 1 else few if 2 <= n <= 4 else many


def li(xs):
    return "".join(f"<li>{html.escape(x)}</li>" for x in xs)


def tile(b):
    code = b["name"].split(" ")[0]
    return (f'<a class="tile" data-board="{html.escape(b["name"])}"><img src="thumbs/{slug(b["name"])}.jpg" alt="">'
            f'<span class="cap"><b>{code}</b> {html.escape(SHORT[code])}</span></a>')


def otile(b):
    code = b["name"].split(" ")[0]
    return (f'<div class="tile"><img src="thumbs/{slug(b["name"])}.jpg" alt="">'
            f'<span class="cap"><b>{code}</b> {html.escape(OTHER[code])}</span></div>')


def site(g):
    bs = [b for b in pages if b["group"] == g]
    main = [b for b in bs if b["name"][:2].isdigit() and int(b["name"][:2]) <= 10]
    return main, [b for b in bs if b not in main]


